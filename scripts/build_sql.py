"""Build idempotent Supabase SQL from the CSV files in mock_data/.

mock_data/master/*.csv  -> supabase/seed/01_master_data.sql
mock_data/events/*.csv  -> supabase/seed/02_events.sql
mock_data/config/refresh_policy.json -> supabase/scenarios/refresh_demo_environment.sql

Event times are hour offsets from midnight (UTC) of the day the SQL runs.
"""

from __future__ import annotations

import argparse
import csv
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MOCK = ROOT / "mock_data"
OUT = ROOT / "supabase" / "seed"

ANCHOR = "date_trunc('day', now())"
EVENT_ORDER = ["PICK_STARTED", "PICK_SHORT", "PICKED", "STAGED", "DISPATCHED", "ETA_CHANGED", "DELIVERED", "FAILED"]


def read(folder: str, name: str) -> tuple[list[str], list[dict[str, str]]]:
    with open(MOCK / folder / f"{name}.csv", newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        return list(reader.fieldnames or []), list(reader)


def lit(value: str) -> str:
    return "NULL" if value == "" else "'" + value.replace("'", "''") + "'"


def values(cols: list[str], rows: list[dict[str, str]]) -> str:
    body = ",\n    ".join("(" + ", ".join(lit(r[c]) for c in cols) + ")" for r in rows)
    return f"(VALUES\n    {body}\n) AS v({', '.join(cols)})"


def hours(expr: str) -> str:
    return f"{ANCHOR} + ({expr})::numeric * interval '1 hour'"


def simple_upsert(schema_table: str, folder: str, name: str, conflict: str, casts: dict[str, str] | None = None) -> str:
    cols, rows = read(folder, name)
    casts = casts or {}
    select = ", ".join(f"v.{c}::{casts[c]}" if c in casts else f"v.{c}" for c in cols)
    updates = ", ".join(f"{c} = EXCLUDED.{c}" for c in cols if c != conflict)
    return (
        f"INSERT INTO {schema_table} ({', '.join(cols)})\n"
        f"SELECT {select}\nFROM {values(cols, rows)}\n"
        f"ON CONFLICT ({conflict}) DO UPDATE SET {updates};\n"
    )


def build_master() -> str:
    parts = ["-- GENERATED by scripts/build_sql.py from mock_data/master. Do not edit.\n"]
    parts.append(simple_upsert("core.wms_distribution_centers", "master", "distribution_centers", "code"))
    parts.append(simple_upsert("core.tms_carriers", "master", "carriers", "code"))
    parts.append(simple_upsert("core.erp_products", "master", "products", "sku",
                               {"unit_weight_kg": "numeric", "is_bulky": "boolean"}))
    parts.append(simple_upsert("core.erp_customers", "master", "customers", "customer_number",
                               {"sla_hours": "integer"}))

    cols, rows = read("master", "delivery_sites")
    parts.append(
        "INSERT INTO core.erp_delivery_sites (customer_id, site_name, address_line, postcode, city, access_notes, contact_name, contact_phone)\n"
        "SELECT c.id, v.site_name, v.address_line, v.postcode, v.city, v.access_notes, v.contact_name, v.contact_phone\n"
        f"FROM {values(cols, rows)}\n"
        "JOIN core.erp_customers c ON c.customer_number = v.customer_number\n"
        "WHERE NOT EXISTS (\n"
        "    SELECT 1 FROM core.erp_delivery_sites ds\n"
        "    WHERE ds.customer_id = c.id AND ds.address_line = v.address_line\n"
        ");\n"
    )

    cols, rows = read("master", "inventory_balances")
    parts.append(
        "INSERT INTO operations.wms_inventory_balances (distribution_center_id, product_id, on_hand_quantity, reserved_quantity)\n"
        "SELECT dc.id, p.id, v.on_hand_quantity::numeric, v.reserved_quantity::numeric\n"
        f"FROM {values(cols, rows)}\n"
        "JOIN core.wms_distribution_centers dc ON dc.code = v.dc_code\n"
        "JOIN core.erp_products p ON p.sku = v.sku\n"
        "ON CONFLICT (distribution_center_id, product_id) DO UPDATE SET\n"
        "    on_hand_quantity = EXCLUDED.on_hand_quantity,\n"
        "    reserved_quantity = EXCLUDED.reserved_quantity,\n"
        "    updated_at = now();\n"
    )
    return "\n".join(parts)


def build_events() -> str:
    parts = ["-- GENERATED by scripts/build_sql.py from mock_data/events. Do not edit.\n"]

    cols, rows = read("events", "sales_orders")
    parts.append(
        "INSERT INTO commercial.erp_sales_orders (order_number, customer_id, delivery_site_id, distribution_center_id, ordered_at, promised_window_start, promised_window_end, status, currency)\n"
        "SELECT v.order_number, c.id, ds.id, dc.id,\n"
        f"    {hours('v.ordered_offset_hours')},\n"
        f"    {hours('v.window_start_offset_hours')},\n"
        f"    {hours('v.window_start_offset_hours::numeric + v.window_hours::numeric')},\n"
        "    v.status, v.currency\n"
        f"FROM {values(cols, rows)}\n"
        "JOIN core.erp_customers c ON c.customer_number = v.customer_number\n"
        "JOIN core.erp_delivery_sites ds ON ds.customer_id = c.id AND ds.address_line = v.site_address_line\n"
        "JOIN core.wms_distribution_centers dc ON dc.code = v.dc_code\n"
        "ON CONFLICT (order_number) DO UPDATE SET\n"
        "    ordered_at = EXCLUDED.ordered_at,\n"
        "    promised_window_start = EXCLUDED.promised_window_start,\n"
        "    promised_window_end = EXCLUDED.promised_window_end,\n"
        "    status = EXCLUDED.status;\n"
    )

    cols, rows = read("events", "sales_order_lines")
    parts.append(
        "INSERT INTO commercial.erp_sales_order_lines (sales_order_id, product_id, line_number, quantity_ordered, unit_price)\n"
        "SELECT so.id, p.id, v.line_number::integer, v.quantity_ordered::numeric, v.unit_price::numeric\n"
        f"FROM {values(cols, rows)}\n"
        "JOIN commercial.erp_sales_orders so ON so.order_number = v.order_number\n"
        "JOIN core.erp_products p ON p.sku = v.sku\n"
        "ON CONFLICT (sales_order_id, line_number) DO UPDATE SET\n"
        "    product_id = EXCLUDED.product_id,\n"
        "    quantity_ordered = EXCLUDED.quantity_ordered,\n"
        "    unit_price = EXCLUDED.unit_price;\n"
    )

    cols, rows = read("events", "deliveries")
    parts.append(
        "INSERT INTO operations.wms_fulfillments (sales_order_id, status)\n"
        "SELECT so.id, 'PENDING'\n"
        f"FROM {values(['order_number'], rows)}\n"
        "JOIN commercial.erp_sales_orders so ON so.order_number = v.order_number\n"
        "ON CONFLICT (sales_order_id) DO NOTHING;\n"
    )
    parts.append(
        "INSERT INTO operations.wms_fulfillment_lines (fulfillment_id, sales_order_line_id, quantity_picked)\n"
        "SELECT f.id, sol.id, 0\n"
        "FROM operations.wms_fulfillments f\n"
        "JOIN commercial.erp_sales_order_lines sol ON sol.sales_order_id = f.sales_order_id\n"
        "ON CONFLICT (fulfillment_id, sales_order_line_id) DO NOTHING;\n"
    )
    parts.append(
        "INSERT INTO operations.tms_deliveries (fulfillment_id, delivery_number, carrier_id, tracking_reference, vehicle_type, status, planned_dispatch_at, planned_eta)\n"
        "SELECT f.id, v.delivery_number, car.id, v.tracking_reference, v.vehicle_type, 'PLANNED',\n"
        f"    {hours('v.planned_dispatch_offset_hours')},\n"
        f"    {hours('v.planned_eta_offset_hours')}\n"
        f"FROM {values(cols, rows)}\n"
        "JOIN commercial.erp_sales_orders so ON so.order_number = v.order_number\n"
        "JOIN operations.wms_fulfillments f ON f.sales_order_id = so.id\n"
        "JOIN core.tms_carriers car ON car.code = v.carrier_code\n"
        "ON CONFLICT (fulfillment_id) DO UPDATE SET\n"
        "    carrier_id = EXCLUDED.carrier_id,\n"
        "    tracking_reference = EXCLUDED.tracking_reference,\n"
        "    vehicle_type = EXCLUDED.vehicle_type,\n"
        "    planned_dispatch_at = EXCLUDED.planned_dispatch_at,\n"
        "    planned_eta = EXCLUDED.planned_eta;\n"
    )

    _, events = read("events", "delivery_events")
    events.sort(key=lambda e: (float(e["offset_hours"]), EVENT_ORDER.index(e["event_type"])))
    parts.append("-- Delivery events, in chronological order.")
    for e in events:
        parts.append(event_sql(e))
    return "\n".join(parts)


def event_sql(e: dict[str, str]) -> str:
    dn = lit(e["delivery_number"])
    at = hours(lit(e["offset_hours"]))
    kind = e["event_type"]
    fulfillment = (
        "UPDATE operations.wms_fulfillments f SET status = '{status}', updated_at = now()\n"
        f"FROM operations.tms_deliveries d WHERE d.fulfillment_id = f.id AND d.delivery_number = {dn};"
    )
    if kind == "PICK_STARTED":
        return fulfillment.format(status="PICKING")
    if kind == "PICKED":
        return (
            fulfillment.format(status="PICKED") + "\n"
            "UPDATE operations.wms_fulfillment_lines fl SET quantity_picked = sol.quantity_ordered\n"
            "FROM operations.tms_deliveries d, commercial.erp_sales_order_lines sol\n"
            f"WHERE d.delivery_number = {dn} AND fl.fulfillment_id = d.fulfillment_id\n"
            "  AND sol.id = fl.sales_order_line_id AND fl.short_reason IS NULL;"
        )
    if kind == "PICK_SHORT":
        return (
            f"UPDATE operations.wms_fulfillment_lines fl SET quantity_picked = {lit(e['quantity'])}::numeric, short_reason = {lit(e['reason'])}\n"
            "FROM operations.tms_deliveries d, commercial.erp_sales_order_lines sol, core.erp_products p\n"
            f"WHERE d.delivery_number = {dn} AND fl.fulfillment_id = d.fulfillment_id\n"
            f"  AND sol.id = fl.sales_order_line_id AND p.id = sol.product_id AND p.sku = {lit(e['sku'])};"
        )
    if kind == "STAGED":
        return fulfillment.format(status="STAGED")
    delivery = f"UPDATE operations.tms_deliveries SET {{sets}}, updated_at = now() WHERE delivery_number = {dn};"
    if kind == "DISPATCHED":
        return delivery.format(sets=f"status = 'IN_PROGRESS', dispatched_at = {at}, current_eta = COALESCE(current_eta, planned_eta)")
    if kind == "ETA_CHANGED":
        return delivery.format(sets=f"current_eta = {hours(lit(e['eta_offset_hours']))}")
    if kind == "DELIVERED":
        return delivery.format(sets=f"status = 'DELIVERED', delivered_at = {at}")
    if kind == "FAILED":
        return delivery.format(sets="status = 'FAILED'")
    raise ValueError(f"Unknown event_type: {kind}")


RESET_MODES = ("EVENTS_ONLY", "FULL")
CRON_FIELD = re.compile(r"^[\d*/,\-]+$")


def load_policy() -> dict:
    policy = json.loads((MOCK / "config" / "refresh_policy.json").read_text(encoding="utf-8"))
    if policy["reset_mode"] not in RESET_MODES:
        raise ValueError(f"reset_mode must be one of {RESET_MODES}")
    fields = policy["schedule_cron"].split()
    if len(fields) != 5 or not all(CRON_FIELD.match(f) for f in fields):
        raise ValueError("schedule_cron must be a 5-field cron expression, e.g. '0 1 * * *'")
    if not re.fullmatch(r"[\w\-]+", policy["job_name"]):
        raise ValueError("job_name may contain only letters, digits, '_' and '-'")
    return policy


def build_refresh(master_sql: str, events_sql: str) -> str:
    policy = load_policy()
    job, cron, mode = lit(policy["job_name"]), lit(policy["schedule_cron"]), policy["reset_mode"]
    body = "\n".join(
        "    " + line if line else line for line in (master_sql + "\n" + events_sql).splitlines()
    )
    schedule = (
        f"SELECT cron.schedule({job}, {cron}, $job$SELECT operations.refresh_demo_environment({lit(mode)});$job$);"
        if policy["enabled"]
        else f"SELECT cron.unschedule(jobid) FROM cron.job WHERE jobname = {job};"
    )
    return f"""-- GENERATED by scripts/build_sql.py from mock_data. Do not edit.
-- Policy: reset_mode={mode}, schedule={policy['schedule_cron']}, enabled={str(policy['enabled']).lower()}
--
-- EVENTS_ONLY: clears orders, fulfillments, deliveries and inventory, keeps master data.
-- FULL:        also clears customers, sites, products, carriers and distribution centers.
-- Master data and events are then reloaded from mock_data.

CREATE OR REPLACE FUNCTION operations.refresh_demo_environment(p_reset_mode text DEFAULT {lit(mode)})
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, core, commercial, operations
AS $$
BEGIN
    IF p_reset_mode NOT IN ('EVENTS_ONLY', 'FULL') THEN
        RAISE EXCEPTION 'p_reset_mode must be EVENTS_ONLY or FULL';
    END IF;

    DELETE FROM operations.tms_deliveries;
    DELETE FROM operations.wms_fulfillment_lines;
    DELETE FROM operations.wms_fulfillments;
    DELETE FROM commercial.erp_sales_order_lines;
    DELETE FROM commercial.erp_sales_orders;
    DELETE FROM operations.wms_inventory_balances;

    IF p_reset_mode = 'FULL' THEN
        DELETE FROM core.erp_delivery_sites;
        DELETE FROM core.erp_customers;
        DELETE FROM core.erp_products;
        DELETE FROM core.tms_carriers;
        DELETE FROM core.wms_distribution_centers;
    END IF;

{body}
END;
$$;

-- Applies the schedule from refresh_policy.json; requires the pg_cron extension.
{schedule}
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated SQL differs from committed files")
    args = parser.parse_args()

    master_sql, events_sql = build_master(), build_events()
    outputs = {
        OUT / "01_master_data.sql": master_sql,
        OUT / "02_events.sql": events_sql,
        ROOT / "supabase" / "scenarios" / "refresh_demo_environment.sql": build_refresh(master_sql, events_sql),
    }
    stale = []
    for path, sql in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != sql:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(sql, encoding="utf-8", newline="\n")
            print(f"Wrote {path.relative_to(ROOT)}")
    if stale:
        print("Out of date: " + ", ".join(str(p.relative_to(ROOT)) for p in stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
